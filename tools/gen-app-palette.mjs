// Writes lib/core/theme/app_palette_defaults.dart from the colour catalogue in packages/contracts (build it first), so the
// app starts from exactly the colours the console edits. Run after changing APP_TOKENS or APP_SHARED:
//   pnpm --filter @gradeon/contracts build && node tools/gen-app-palette.mjs
import { writeFileSync } from 'node:fs';
import { resolveApp } from '../packages/contracts/dist/index.js';

const argb = (hex) => {
  const h = hex.replace('#', '').toUpperCase();
  return `0x${h.length === 8 ? h.slice(6) : 'FF'}${h.slice(0, 6)}`;
};
const mode = (m) => Object.entries(resolveApp({}, m)).map(([k, v]) => `    '${k}': Color(${argb(v)}),`).join('\n');
const dart = `// Generated by tools/gen-app-palette.mjs from packages/contracts/src/theme.ts. Do not edit by hand.
import 'package:flutter/painting.dart';

/// The design's colours for each app theme, before a school changes any of them in the console.
const appPaletteDefaults = <String, Map<String, Color>>{
  'light': {
${mode('light')}
  },
  'dark': {
${mode('dark')}
  },
  'amoled': {
${mode('amoled')}
  },
};
`;
writeFileSync(new URL('../lib/core/theme/app_palette_defaults.dart', import.meta.url), dart);
console.log('wrote lib/core/theme/app_palette_defaults.dart');
