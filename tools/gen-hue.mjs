// Writes the starting colours of Gradeon Hue from packages/contracts/src/hue.ts (build it first):
//   packages/web-ui/src/hue.css             the console's seed, until a school's own seed is put on the page (useHue)
//   lib/core/theme/app_palette_defaults.dart the default brand colour's seed, until the app has the school's palette
//   pnpm --filter @gradeon/contracts build && node tools/gen-hue.mjs
import { writeFileSync } from 'node:fs';
import { CONSOLE_HUE, DEFAULT_BRAND, appTokens, hueCss, hueOf } from '../packages/contracts/dist/index.js';

writeFileSync(new URL('../packages/web-ui/src/hue.css', import.meta.url),
  `/* Generated by tools/gen-hue.mjs from packages/contracts/src/hue.ts (seed ${CONSOLE_HUE}). Do not edit by hand. */\n${hueCss(CONSOLE_HUE).replace(/\}/g, '}\n')}`);

const argb = (hex) => `0x${hex.length === 9 ? hex.slice(7, 9) : 'FF'}${hex.slice(1, 7)}`.toUpperCase().replace('0X', '0x');
const seed = hueOf(DEFAULT_BRAND);
const mode = (m) => Object.entries(appTokens(seed, m)).map(([k, v]) => `    '${k}': Color(${argb(v)}),`).join('\n');
writeFileSync(new URL('../lib/core/theme/app_palette_defaults.dart', import.meta.url), `// Generated by tools/gen-hue.mjs from packages/contracts/src/hue.ts (seed ${seed}). Do not edit by hand.
import 'package:flutter/painting.dart';

/// Gradeon Hue's colours for each app theme, before the app has the school's own palette.
const appPaletteDefaults = <String, Map<String, Color>>{
  'light': {
${mode('light')}
  },
  'dark': {
${mode('dark')}
  },
  'amoled': {
${mode('amoled')}
  },
};
`);
console.log('wrote packages/web-ui/src/hue.css and lib/core/theme/app_palette_defaults.dart');
